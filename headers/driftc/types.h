#ifndef DRIFTC_TYPES_H
#define DRIFTC_TYPES_H

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

// signed integers
typedef int8_t   i8;
typedef int16_t  i16;
typedef int32_t  i32;
typedef int64_t  i64;

// unsigned integer
typedef uint8_t  ui8;
typedef uint16_t ui16;
typedef uint32_t ui32;
typedef uint64_t ui64;

// floating point types
typedef float  f32;
typedef double f64;

// size type
typedef size_t usize;

typedef bool bool_t;

#endif
